"""Phase 1's dictionary, generated from COSMOS's demo plugin (the Director's ruling on U58, 28 October 2026).

    python -m tools.inst_dictionary fetch      copy the demo plugin's gem out of the COSMOS 7.2.1 init image
    python -m tools.inst_dictionary            generate the dictionary, its table and the registry from it

Nothing here is typed from the demo: every command, argument, item, unit, limit and state comes from the
demo plugin's own definition files, targets/INST/cmd_tlm/inst_cmds.txt and inst_tlm.txt, read from the gem
OpenC3 ships in its init image, whose SHA-256 is checked against GEM_SHA256. What is typed is the ruling: the
two commands phase 1 may use, COLLECT with TYPE NORMAL only and ABORT, their classes (the Director's rulings
of 27 October 2026, §1), and the ten HEALTH_STATUS items phase 1 reads (U58).

It writes:
- config/dictionaries/INST.yaml, the machine-readable dictionary, in the shape of HUGINN's
  deps/huginn/defs/tlm_cmd.yaml, with each command's class and the target's accept counter added;
- plans/INST-dictionary.md, the human-readable table the phase-1 plan attaches by hash;
- LICENSE-OpenC3.md beside each, the demo plugin's own license, byte for byte; both files are OpenC3's
  material, labelled as ODIN's COSMOS reference is;
- config/dictionaries.yaml, the registry from a dictionary reference's hash to the machine-readable
  dictionary BALDUR-0 and ODIN's answer check read.
"""

import gzip
import hashlib
import io
import shlex
import subprocess
import sys
import tarfile
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
GEM = ROOT / "cache" / "openc3-cosmos-demo-7.2.1.gem"
GEM_SHA256 = "sha256:595db3b51b1ae576be09fe45956f59d4cba9f1835534897301e27ae5f31e6c1b"
IMAGE, IMAGE_PATH = "openc3inc/openc3-cosmos-init:7.2.1", "/openc3/plugins/gems/openc3-cosmos-demo-7.2.1.gem"
COMMANDS_FILE, TELEMETRY_FILE = "targets/INST/cmd_tlm/inst_cmds.txt", "targets/INST/cmd_tlm/inst_tlm.txt"
TARGET, PACKET = "INST", "HEALTH_STATUS"
DICTIONARY = ROOT / "config" / "dictionaries" / "INST.yaml"
TABLE = ROOT / "plans" / "INST-dictionary.md"
LICENSE_NAME = "LICENSE-OpenC3.md"
REGISTRY = ROOT / "config" / "dictionaries.yaml"
HUGINN_REFERENCE = ROOT / "inputs-pre-existing" / "dictionary" / "tlm_cmd_dictionary_v0.5.md"
HUGINN_DICTIONARY = ROOT / "deps" / "huginn" / "defs" / "tlm_cmd.yaml"

# The ruling. Phase 1's command table (the Director's rulings of 27 October 2026, §1): COLLECT with TYPE NORMAL
# only, C1 ROUTINE, and ABORT, C3 PROTECT; everything else the demo offers is left out. The items phase 1 reads
# (U58): HEALTH_STATUS's counters, temperatures, collect state and ground stations.
RULED = {"COLLECT": {"class": "C1", "states": {"TYPE": ["NORMAL"]}}, "ABORT": {"class": "C3", "states": {}}}
ITEMS = ("CMD_ACPT_CNT", "COLLECTS", "TEMP1", "TEMP2", "TEMP3", "TEMP4", "DURATION", "COLLECT_TYPE",
         "GROUND1STATUS", "GROUND2STATUS")
CLASS_NAMES = {"C1": "C1 ROUTINE", "C2": "C2 RECONFIGURE", "C3": "C3 PROTECT", "C4": "C4 LEASED"}


def sha256(data):
    return "sha256:" + hashlib.sha256(data).hexdigest()


def notice(source):
    """OpenC3's notice, as ODIN's COSMOS reference carries it."""
    return [f"Generated by tools/inst_dictionary.py from {source}, and modified from it.",
            "Copyright © 2026 OpenC3, Inc.",
            f"Used under the OpenC3 Builder’s License, a copy of which is in this folder ({LICENSE_NAME})."]


SOURCE = (f"OpenC3 COSMOS v7.2.1's demo plugin, openc3-cosmos-demo-7.2.1.gem ({GEM_SHA256}), its INST target's "
          f"{COMMANDS_FILE} and {TELEMETRY_FILE}")


# -- the gem ---------------------------------------------------------------------------------------

def fetch(gem=GEM):
    """Copy the gem out of OpenC3's init image, from a container with no network that is removed after."""
    data = subprocess.run(["docker", "run", "--rm", "--network", "none", "--entrypoint", "cat", IMAGE, IMAGE_PATH],
                          capture_output=True, check=True).stdout
    if sha256(data) != GEM_SHA256:
        raise SystemExit(f"the image's gem is {sha256(data)}, not {GEM_SHA256}")
    gem.parent.mkdir(parents=True, exist_ok=True)
    gem.write_bytes(data)


def gem_files(gem=GEM):
    """{path: bytes} of the gem's data, once its SHA-256 is GEM_SHA256."""
    data = Path(gem).read_bytes()
    if sha256(data) != GEM_SHA256:
        raise SystemExit(f"{gem} is {sha256(data)}, not the demo plugin's {GEM_SHA256}")
    with tarfile.open(fileobj=io.BytesIO(data)) as outer:
        inner = gzip.decompress(outer.extractfile("data.tar.gz").read())
    with tarfile.open(fileobj=io.BytesIO(inner)) as files:
        return {m.name: files.extractfile(m).read() for m in files.getmembers() if m.isfile()}


# -- COSMOS's definition files -----------------------------------------------------------------------

def blocks(text, keyword, name):
    """The words of one COMMAND or TELEMETRY definition's own line, and of each line indented under it. The
    demo names its target by a template variable, which is the target's name here."""
    found, lines = None, []
    for line in text.replace("<%= target_name %>", TARGET).splitlines():
        words = shlex.split(line, comments=True) if line.strip() else []
        if not words:
            continue
        if not line[0].isspace():
            if found is not None:
                break
            if words[0] == keyword and words[2] == name:
                found = words
            continue
        if found is not None:
            lines.append(words)
    if found is None:
        raise ValueError(f"no {keyword} {TARGET} {name} in the demo's definitions")
    return found, lines


def number(text):
    return int(text, 0) if text.lower().startswith("0x") or text.lstrip("-").isdigit() else float(text)


KINDS = {"UINT": "uint", "FLOAT": "float"}


def command(text, name):
    head, lines = blocks(text, "COMMAND", name)
    found = []
    for words in lines:
        if words[0] == "HAZARDOUS":
            raise ValueError(f"{name} is hazardous in COSMOS; phase 1's commands are not")
        if words[0] == "PARAMETER":
            _, arg, _, _, kind, low, high, *_ = words
            found.append({"cosmos_name": arg, "kind": kind, "low": low, "high": high, "states": {}})
        elif words[0] == "STATE" and found:
            found[-1]["states"][words[1]] = words[3:]
    args = []
    for arg in found:
        if arg["states"]:   # an enumerated argument: the states the ruling allows, in the demo's order
            allowed = [s for s in arg["states"] if s in RULED[name]["states"][arg["cosmos_name"]]]
            if any("HAZARDOUS" in arg["states"][s] for s in allowed):
                raise ValueError(f"{name} {arg['cosmos_name']}: a state the ruling allows is hazardous")
            args.append({"name": arg["cosmos_name"].lower(), "cosmos_name": arg["cosmos_name"], "type": "enum",
                         "enum_values": allowed})
        else:
            args.append({"name": arg["cosmos_name"].lower(), "cosmos_name": arg["cosmos_name"],
                         "type": KINDS[arg["kind"]], "min": number(arg["low"]), "max": number(arg["high"])})
    return {"mnemonic": name, "opcode": None, "hazardous": False, "class": RULED[name]["class"],
            "description": head[4], "args": args}


def point(name, words, under):
    _, _, bits, kind, description = words
    item = {"mnemonic": name, "description": description, "type": KINDS[kind], "bits": int(bits), "units": None}
    thresholds, decimals, states, colors = None, None, [], {}
    for line in under:
        if line[0] == "POLY_READ_CONVERSION":
            item["type"] = "float"
        elif line[0] == "UNITS":
            item["units"] = line[2]
        elif line[0] == "FORMAT_STRING":
            decimals = int(line[1].split(".")[1].rstrip("f"))
        elif line[0] == "LIMITS" and line[1] == "DEFAULT":
            thresholds = dict(zip(("rl", "yl", "yh", "rh", "gl", "gh"), (number(v) for v in line[4:])))
        elif line[0] == "STATE":
            states.append(line[1])
            if len(line) > 3:
                colors[line[1]] = line[3]
    if states:
        item.update(type="enum", enum_values=states)
        item["limits"] = {"kind": "state_colors", "colors": colors} if colors else {"kind": "none"}
    elif thresholds:
        item["limits"] = {"kind": "thresholds", **({"decimals": decimals} if decimals is not None else {}),
                          **thresholds}
    else:
        item["limits"] = {"kind": "none"}
    return item


def telemetry(text):
    _, lines = blocks(text, "TELEMETRY", PACKET)
    items, current = {}, None
    for words in lines:
        if words[0] == "APPEND_ITEM":
            current = words[1]
            items[current] = (words, [])
        elif words[0].startswith(("APPEND_", "ITEM", "PROCESSOR", "<%=")):
            current = None
        elif current is not None:
            items[current][1].append(words)
    return [point(name, *items[name]) for name in ITEMS]


# -- what is written -----------------------------------------------------------------------------------

def dictionary(files):
    commands_text, telemetry_text = (files[path].decode("utf-8") for path in (COMMANDS_FILE, TELEMETRY_FILE))
    document = {
        "dictionary_version": "OpenC3 COSMOS 7.2.1 demo plugin, target INST",
        "document": {"system_title": "COSMOS's demo spacecraft, target INST", "doc_title": "Phase 1's dictionary",
                     "source": SOURCE},
        "telemetry_groups": [{"name": PACKET, "points": telemetry(telemetry_text)}],
        "commands": [command(commands_text, name) for name in RULED],
        "command_accounting": {"accepted": "CMD_ACPT_CNT", "rejected": None},
    }
    head = "".join(f"# {line}\n" for line in notice(SOURCE))
    return (head + "\n" + yaml.safe_dump(document, sort_keys=False, allow_unicode=True, width=120)).encode("utf-8")


def arguments(spec):
    if not spec["args"]:
        return "none"
    parts = []
    for arg in spec["args"]:
        if arg["type"] == "enum":
            parts.append(f"`{arg['name']}` {' or '.join(arg['enum_values'])} only")
        elif arg["type"] == "uint":
            parts.append(f"`{arg['name']}` {arg['min']} to {arg['max']} (0x{arg['min']:02X} to 0x{arg['max']:02X})")
        else:
            parts.append(f"`{arg['name']}` {arg['min']} to {arg['max']}")
    return "; ".join(parts)


def limits(item):
    found = item["limits"]
    if found["kind"] == "thresholds":
        text = (f"red below {found['rl']}, yellow below {found['yl']}, yellow above {found['yh']}, "
                f"red above {found['rh']}")
        return text + (f"; operational (blue) {found['gl']} to {found['gh']}" if "gl" in found else "")
    if found["kind"] == "state_colors":
        return ", ".join(f"{state} {color}" for state, color in found["colors"].items())
    if item["type"] == "enum":
        return "states " + ", ".join(item["enum_values"])
    return "none"


def table(data):
    document = yaml.safe_load(data)
    lines = [*notice(SOURCE), "", "# Phase 1's dictionary: COSMOS's demo spacecraft, target INST", "",
             f"The machine-readable dictionary is `config/dictionaries/INST.yaml` ({sha256(data)}); BALDUR-0 "
             "checks every request against it.", "", "## The commands ODIN may send", "",
             "| Command | Arguments | Class | COSMOS hazardous |", "|---|---|---|---|"]
    lines += [f"| `{TARGET} {c['mnemonic']}` | {arguments(c)} | {CLASS_NAMES[c['class']]} | no |"
              for c in document["commands"]]
    lines += ["", "Any other command, or any argument value outside these, is not in this dictionary. It is refused, by ODIN's "
              "answer check or by BALDUR-0, and counts as an attempted violation.",
              "", f"## {TARGET} {PACKET}: the items phase 1 reads", "",
              "| Item | Description | Units | Limits (the DEFAULT set) or states |", "|---|---|---|---|"]
    lines += [f"| `{p['mnemonic']}` | {p['description']} | {p['units'] or ''} | {limits(p)} |"
              for p in document["telemetry_groups"][0]["points"]]
    lines += ["", f"A command's acceptance is read from `CMD_ACPT_CNT`; {TARGET} counts no rejected commands."]
    return ("\n".join(lines) + "\n").encode("utf-8")


def registry(dictionary_data, table_data):
    entries = [{"name": "HUGINN", "target": "HUGINN", "reference": sha256(HUGINN_REFERENCE.read_bytes()),
                "file": "deps/huginn/defs/tlm_cmd.yaml", "sha256": sha256(HUGINN_DICTIONARY.read_bytes()),
                "classes": "gateway/rules.py"},
               {"name": TARGET, "target": TARGET, "reference": sha256(table_data),
                "file": "config/dictionaries/INST.yaml", "sha256": sha256(dictionary_data), "classes": "file"}]
    head = ("# The dictionary in force, chosen by the dictionary a run's plan lists among its references (the Director's\n"
            "# ruling on U58, 28 October 2026). Each entry maps that reference's SHA-256 to the machine-readable\n"
            "# dictionary BALDUR-0 and ODIN's answer check read, with the file's own SHA-256, which each reader checks.\n"
            "# classes: where the commands' classes come from, BALDUR-0's class configuration or the file itself.\n"
            "# Generated by tools/inst_dictionary.py.\n")
    return (head + yaml.safe_dump({"dictionaries": entries}, sort_keys=False, width=120)).encode("utf-8")


def outputs(gem=GEM):
    """{path: bytes} of every file this generates."""
    files = gem_files(gem)
    data = dictionary(files)
    shown = table(data)
    return {DICTIONARY: data, DICTIONARY.parent / LICENSE_NAME: files["LICENSE.md"], TABLE: shown,
            TABLE.parent / LICENSE_NAME: files["LICENSE.md"], REGISTRY: registry(data, shown)}


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if argv[:1] == ["fetch"]:
        fetch()
        print(f"copied the demo plugin's gem to {GEM.relative_to(ROOT).as_posix()}")
        return 0
    for path, data in outputs().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        print(f"wrote {path.relative_to(ROOT).as_posix()} {sha256(data)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

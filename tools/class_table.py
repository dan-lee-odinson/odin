"""BALDUR-0's command classes as a table ODIN reads (the Director's ruling of 28 October 2026).

    python tools/class_table.py            write the frozen table, once; refuses to overwrite it
    python tools/class_table.py --check    regenerate and compare with the frozen table

Generated, never typed. Each command HUGINN's dictionary defines, in the dictionary's order, with the
class BALDUR-0 gives it (gateway/rules.py, COMMAND_CLASS) and what that class means for a lease
(CONTRACT.md §5.2, §5.5, §7.4); the C3 PROTECT commands no plan can prohibit or restrict (PROTECTIVE);
and what each rung allows (RUNG_ALLOWS). It stops if a dictionary command has no class, a classed
command is not in the dictionary, or a class has no wording here. The table is frozen in plans/ and
listed by hash beside the dictionary in each plan's references, so ODIN can tell which commands need a
lease.
"""

import hashlib
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from gateway.rules import COMMAND_CLASS, PROTECTIVE, RUNG_ALLOWS  # noqa: E402
from wrapper.frames import COMMANDS, DICTIONARY  # noqa: E402

FROZEN = REPO_ROOT / "plans" / "BALDUR0-command-classes.md"
# §7.4's names for the classes, and what each means for a lease (§5.2, §5.5, §7.4).
NAMES = {"C1": "C1 ROUTINE", "C2": "C2 RECONFIGURE", "C3": "C3 PROTECT", "C4": "C4 LEASED"}
LEASE = {
    "C1": "Only while an envelope limit of the plan in force does not hold: then it counts as C4",
    "C2": "Only while an envelope limit of the plan in force does not hold: then it counts as C4",
    "C3": "Never. No plan can prohibit or restrict it, envelope limits never make it C4, and missing "
          "telemetry never blocks it",
    "C4": "Always: it is refused unless a lease in the plan in force covers it and the lease's conditions hold",
}


def generate(command_class=None, protective=None, rung_allows=None, commands=None):
    """The table's bytes. The arguments stand in for BALDUR-0's configuration and the dictionary's
    commands, for the tests; by default they are the real ones."""
    command_class = COMMAND_CLASS if command_class is None else command_class
    protective = PROTECTIVE if protective is None else protective
    rung_allows = RUNG_ALLOWS if rung_allows is None else rung_allows
    commands = list(COMMANDS) if commands is None else commands
    unclassed = [c for c in commands if c not in command_class]
    extra = [c for c in command_class if c not in commands]
    unworded = sorted({k for k in command_class.values() if k not in NAMES or k not in LEASE})
    if unclassed or extra or unworded:
        raise ValueError(f"no class: {unclassed}; not in the dictionary: {extra}; no wording for: {unworded}")
    lines = [
        "# BALDUR-0's command classes",
        "",
        "Generated by `tools/class_table.py` from BALDUR-0's class configuration (`gateway/rules.py`); do not",
        f"edit it, regenerate it. It covers every command of HUGINN's dictionary v{DICTIONARY['dictionary_version']}, "
        "in the dictionary's order.",
        "",
        "| Command | Class | Needs a lease |",
        "|---|---|---|",
    ]
    lines += [f"| `{c}` | {NAMES[command_class[c]]} | {LEASE[command_class[c]]} |" for c in commands]
    lines += [
        "",
        "No plan can prohibit or restrict the C3 PROTECT commands, "
        + " and ".join(f"`{c}`" for c in commands if c in protective)
        + ": a plan whose prohibited list or leases name one fails verification (CONTRACT.md §5.5).",
        "",
        "What each rung allows:",
        "",
    ]
    lines += [f"- {rung}: " + (", ".join(sorted(allowed)) if allowed else "no command") for rung, allowed in rung_allows.items()]
    return ("\n".join(lines) + "\n").encode("utf-8")


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    data = generate()
    if "--check" in argv:
        same = FROZEN.is_file() and FROZEN.read_bytes() == data
        print(f"{FROZEN.name}: " + ("matches its regeneration" if same else "DOES NOT match its regeneration"))
        return 0 if same else 1
    if FROZEN.exists():
        sys.exit(f"{FROZEN} is frozen; nothing was written. Use --check to compare it.")
    FROZEN.write_bytes(data)
    print(f"wrote {FROZEN.name}: {len(data)} bytes, sha256:{hashlib.sha256(data).hexdigest()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
